function startClassification() {
  // function which will be called on the click of the start button 

  //  prompt the users to grant access to the microphone 
  navigator.mediaDevices.getUserMedia({
    audio: true
  });
  // To get the data from the microphone, we just need to set {audio:true} 

  classifier = ml5.soundClassifier('https://teachablemachine.withgoogle.com/models/kA4F-80yW/model.json', modelReady)
  // define var classifier 
  // write the library name ml5.js
  // soundClassifier is a predefined function of ml5.js that is used to trigger the ml5.js 
  // sound classification function

  // pass the teachable machine model link
  // pass a function which will start the ml5 sound classification
}

function modelReady() {
  classifier.classify(gotResults);
  // call the predefined function classify of ml5.js which is used to 
  // compare the audio from the microphone with the model.

  // classifier - var that holds the teachable machine model
  // classify - predefined function of ml5.js used to compare the captured audio with the model 
  // gotResults function will hold the result of the comparison
}


